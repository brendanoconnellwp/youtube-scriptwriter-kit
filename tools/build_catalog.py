#!/usr/bin/env python3
"""
Build the skill's catalog.md from your channel data.

    python3 tools/build_catalog.py

Reads:
    data/mine/index.json         (from fetch_channel.py)                  required
    data/mine/summaries.json     (one-line summaries Claude writes, step 2) optional
    data/mine/studio.csv         (YouTube Studio analytics export)         optional
Writes:
    skill/youtube-scriptwriter/catalog.md
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MINE = ROOT / "data" / "mine"
OUT = ROOT / "skill" / "youtube-scriptwriter" / "catalog.md"


def load_studio(path):
    """Map video id -> analytics from a YouTube Studio 'Advanced mode' CSV export."""
    if not path.exists():
        return {}
    rows = {}
    with path.open(newline="", encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            low = {k.strip().lower(): (v or "").strip() for k, v in row.items() if k}
            vid = low.get("content") or low.get("video")
            if not vid or vid.lower() == "total":
                continue

            def pick(*needles):
                for k, v in low.items():
                    if all(n in k for n in needles):
                        return v
                return ""

            rows[vid] = {
                "ctr": pick("click-through"),
                "avg_pct": pick("average percentage viewed"),
                "avg_dur": pick("average view duration"),
                "subs": pick("subscribers"),
            }
    return rows


def main():
    idx_path = MINE / "index.json"
    if not idx_path.exists():
        sys.exit("No data/mine/index.json yet. Run tools/fetch_channel.py first.")
    index = json.loads(idx_path.read_text(encoding="utf-8"))
    summaries_path = MINE / "summaries.json"
    summaries = json.loads(summaries_path.read_text(encoding="utf-8")) if summaries_path.exists() else {}
    studio = load_studio(MINE / "studio.csv")

    videos = sorted(index.values(), key=lambda v: v.get("upload_date") or "", reverse=True)
    longs = [v for v in videos if v.get("format") != "short"]
    views_sorted = sorted((v.get("views") or 0 for v in longs), reverse=True)
    top_cut = views_sorted[max(0, len(views_sorted) // 5 - 1)] if views_sorted else 0

    lines = [
        "# Channel catalog",
        "",
        "Every published video, newest first. Generated by tools/build_catalog.py; don't hand-edit.",
        f"★ = top 20% of long-form videos by views (≥ {top_cut:,}).",
        "Use this to avoid repeating a video, to find callbacks/end-screen links, and to see which topics perform.",
        "",
    ]
    has_studio = bool(studio)
    header = "| Date | Title | Views | Min |" + (" CTR | Avg % viewed |" if has_studio else "") + " Summary | Tags | Link |"
    lines += [header, "|" + "---|" * (header.count("|") - 1)]
    for v in videos:
        s = summaries.get(v["id"], {})
        if isinstance(s, str):
            s = {"summary": s}
        star = "★ " if v.get("format") != "short" and (v.get("views") or 0) >= top_cut and top_cut else ""
        short = " (Short)" if v.get("format") == "short" else ""
        title = (v.get("title") or "").replace("|", "/")
        row = f"| {v.get('upload_date','')} | {star}{title}{short} | {v.get('views') or 0:,} | {v.get('duration_min','')} |"
        if has_studio:
            a = studio.get(v["id"], {})
            row += f" {a.get('ctr','')} | {a.get('avg_pct','')} |"
        summary = (s.get("summary") or "").replace("|", "/")
        tags = ", ".join(s.get("topics", [])).replace("|", "/")
        row += f" {summary} | {tags} | {v.get('url','')} |"
        lines.append(row)

    missing = [v for v in videos if v["id"] not in summaries]
    if missing:
        lines += ["", f"_{len(missing)} videos have no summary yet; run prompts/02-summaries.md in Claude Code._"]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(videos)} videos"
          f"{', with Studio analytics' if has_studio else ''}"
          f"{f', {len(missing)} missing summaries' if missing else ''}.")


if __name__ == "__main__":
    main()
